public class tallerfor1 {
    public static void main(String[] args) {

        System.out.println("Números en orden ascendente:");

        for (int i = 0; i <= 100; i++) {
            System.out.println(i);
        }

        System.out.println("Números en orden descendente:");

        for (int i = 100; i >= 0; i--) {
            System.out.println(i);
        }
    }
}

